import Foundation
import CryptoKit
import CommonCrypto

/// End-to-end encryption for DMs, ported to match `apps/web/src/lib/e2ee.ts`
/// **byte-for-byte** so native and web users interoperate.
///
/// Scheme (all values must match the web client exactly):
///   • Key:       PBKDF2-SHA-256(password, salt, 250 000 iterations) → 32 bytes
///   • Salt:      16 random bytes, base64
///   • Verifier:  base64( SHA-256( keyBytes ‖ UTF8("zkE2EE/verify-v2") ) )
///   • Cipher:    AES-256-GCM, 12-byte random IV per message
///   • Wire:      "zkE2EE/3:" + base64( iv(12) ‖ ciphertext ‖ tag(16) )
///   • Base64:    standard (RFC 4648) with padding (matches tweetnacl-util)
///
/// WebCrypto's AES-GCM returns ciphertext WITH the 16-byte tag appended; we
/// reconstruct that layout from CryptoKit's separate `ciphertext` + `tag`.
enum E2EE {
    static let wirePrefixV3 = "zkE2EE/3:"
    static let wirePrefixV2 = "zkE2EE/2:" // legacy XSalsa20 — recognized, not decryptable
    static let wirePrefixV1 = "zkE2EE/1:" // legacy per-user keypair — ditto
    static let keyBytes = 32
    static let ivBytes = 12
    static let tagBytes = 16
    static let saltBytes = 16
    static let pbkdf2Iterations = 250_000
    static let verifierTag = "zkE2EE/verify-v2"

    /// Cheap prefix check — does this content look like an encrypted message?
    static func isEncrypted(_ s: String) -> Bool {
        s.hasPrefix(wirePrefixV3) || s.hasPrefix(wirePrefixV2) || s.hasPrefix(wirePrefixV1)
    }

    /// Only v3 is decryptable; legacy v2/v1 render as tombstones.
    static func isDecryptable(_ s: String) -> Bool { s.hasPrefix(wirePrefixV3) }

    // MARK: Key derivation

    /// Fresh 16-byte PBKDF2 salt, base64 — generated by whoever enables E2EE.
    static func generateSalt() -> String {
        var bytes = [UInt8](repeating: 0, count: saltBytes)
        if SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes) != errSecSuccess {
            for i in bytes.indices { bytes[i] = UInt8.random(in: 0...255) }
        }
        return Data(bytes).base64EncodedString()
    }

    /// Derive the 32-byte shared key from a password + base64 salt.
    /// Same (password, salt) → same key on every device, with no server
    /// exchange of the key itself. Returns raw key bytes, or nil on bad input.
    static func deriveKey(password: String, saltBase64: String) -> Data? {
        guard let salt = Data(base64Encoded: saltBase64) else { return nil }
        let pw = Data(password.utf8)
        return pbkdf2SHA256(password: pw, salt: salt, iterations: pbkdf2Iterations, keyBytes: keyBytes)
    }

    /// base64( SHA-256( key ‖ "zkE2EE/verify-v2" ) ) — lets a client confirm
    /// the typed password is correct without the server learning the key.
    static func verifier(forKey key: Data) -> String {
        var combined = key
        combined.append(Data(verifierTag.utf8))
        let digest = SHA256.hash(data: combined)
        return Data(digest).base64EncodedString()
    }

    // MARK: Encrypt / decrypt

    /// Encrypt plaintext → wire-format string. Returns nil on failure.
    static func encrypt(_ plaintext: String, key: Data) -> String? {
        guard key.count == keyBytes else { return nil }
        do {
            let symKey = SymmetricKey(data: key)
            let nonce = AES.GCM.Nonce() // 12 cryptographically-random bytes
            let sealed = try AES.GCM.seal(Data(plaintext.utf8), using: symKey, nonce: nonce)
            // Match WebCrypto layout: iv ‖ ciphertext ‖ tag.
            var combined = Data(nonce)
            combined.append(sealed.ciphertext)
            combined.append(sealed.tag)
            return wirePrefixV3 + combined.base64EncodedString()
        } catch {
            return nil
        }
    }

    /// Decrypt a wire-format string → plaintext. Returns nil on any failure
    /// (wrong key, tampering, malformed, or a legacy non-v3 format).
    /// Encrypt raw bytes (attachments) with the channel key. Output is
    /// nonce(12) + ciphertext + tag(16) — the same AES-256-GCM layout as
    /// text messages, just unwrapped binary instead of base64 text.
    static func encryptData(_ plaintext: Data, key: Data) -> Data? {
        guard key.count == 32 else { return nil }
        let symKey = SymmetricKey(data: key)
        do {
            let nonce = AES.GCM.Nonce()
            let sealed = try AES.GCM.seal(plaintext, using: symKey, nonce: nonce)
            var out = Data(nonce)
            out.append(sealed.ciphertext)
            out.append(sealed.tag)
            return out
        } catch { return nil }
    }

    /// Decrypt attachment bytes produced by `encryptData`.
    static func decryptData(_ blob: Data, key: Data) -> Data? {
        guard key.count == 32, blob.count > 28 else { return nil }
        let symKey = SymmetricKey(data: key)
        do {
            let nonce = try AES.GCM.Nonce(data: blob.prefix(12))
            let ciphertext = blob.dropFirst(12).dropLast(16)
            let tag = blob.suffix(16)
            let box = try AES.GCM.SealedBox(nonce: nonce, ciphertext: ciphertext, tag: tag)
            return try AES.GCM.open(box, using: symKey)
        } catch { return nil }
    }

    static func decrypt(_ wire: String, key: Data) -> String? {
        guard key.count == keyBytes, wire.hasPrefix(wirePrefixV3) else { return nil }
        let b64 = String(wire.dropFirst(wirePrefixV3.count))
        guard let combined = Data(base64Encoded: b64),
              combined.count >= ivBytes + tagBytes else { return nil }
        let iv = Data(combined.prefix(ivBytes))
        let rest = combined.dropFirst(ivBytes) // ciphertext ‖ tag
        let tag = Data(rest.suffix(tagBytes))
        let ciphertext = Data(rest.dropLast(tagBytes))
        do {
            let symKey = SymmetricKey(data: key)
            let nonce = try AES.GCM.Nonce(data: iv)
            let box = try AES.GCM.SealedBox(nonce: nonce, ciphertext: ciphertext, tag: tag)
            let pt = try AES.GCM.open(box, using: symKey)
            return String(data: pt, encoding: .utf8)
        } catch {
            return nil
        }
    }

    // MARK: PBKDF2 (CommonCrypto — CryptoKit has no PBKDF2)

    private static func pbkdf2SHA256(password: Data, salt: Data, iterations: Int, keyBytes: Int) -> Data? {
        var derived = Data(repeating: 0, count: keyBytes)
        let status: Int32 = derived.withUnsafeMutableBytes { derivedPtr in
            salt.withUnsafeBytes { saltPtr in
                password.withUnsafeBytes { pwPtr in
                    CCKeyDerivationPBKDF(
                        CCPBKDFAlgorithm(kCCPBKDF2),
                        pwPtr.baseAddress?.assumingMemoryBound(to: Int8.self),
                        password.count,
                        saltPtr.baseAddress?.assumingMemoryBound(to: UInt8.self),
                        salt.count,
                        CCPseudoRandomAlgorithm(kCCPRFHmacAlgSHA256),
                        UInt32(iterations),
                        derivedPtr.baseAddress?.assumingMemoryBound(to: UInt8.self),
                        keyBytes
                    )
                }
            }
        }
        return status == Int32(kCCSuccess) ? derived : nil
    }

    // MARK: Key backup (cross-client format)
    //
    // CROSS-CLIENT CONTRACT — identical on-disk shape to web's
    // `exportAllDmKeys` (apps/web/src/lib/e2ee.ts `SharedKeysBackup`), so a
    // backup made on web restores on native and vice-versa:
    //
    //   { "type": "zekktris-e2ee-shared-keys",
    //     "version": 2,
    //     "exportedAt": "<ISO8601>",
    //     "keys": { "<channelId>": { "keyBase64": "<base64(32-byte key)>" } } }
    //
    // The key bytes are the SAME shared-key bytes both clients already store
    // (web in localStorage, native in the Keychain), base64'd — so the file is
    // byte-interchangeable. Web does NOT passphrase-encrypt this file: it is
    // the *no-passphrase* recovery path ("for users who'd rather not remember
    // their passphrase"). Native MUST mirror that — wrapping it in a native-only
    // passphrase would make the two clients' backups mutually unreadable and
    // break the contract. The file itself is therefore sensitive; the UI warns
    // the user and only writes it through a deliberate share action.
    static let keyBackupType = "zekktris-e2ee-shared-keys"
    static let keyBackupVersion = 2

    /// Serialize a channelId → raw-32-byte-key map into the web backup format.
    /// Returns nil when there are no valid keys to write.
    static func encodeKeyBackup(keys: [String: Data], exportedAt: String) -> Data? {
        var keyMap: [String: [String: String]] = [:]
        for (channelId, bytes) in keys where bytes.count == keyBytes {
            keyMap[channelId] = ["keyBase64": bytes.base64EncodedString()]
        }
        guard !keyMap.isEmpty else { return nil }
        let obj: [String: Any] = [
            "type": keyBackupType,
            "version": keyBackupVersion,
            "exportedAt": exportedAt,
            "keys": keyMap,
        ]
        return try? JSONSerialization.data(withJSONObject: obj, options: [.prettyPrinted, .sortedKeys])
    }

    /// Parse a backup file into a channelId → raw-32-byte-key map. Returns nil
    /// only on whole-file failure (bad JSON, wrong type/version, malformed
    /// shape); individual bad entries are skipped (mirrors web's
    /// `importAllDmKeys`, which returns the list of restored ids).
    static func decodeKeyBackup(_ data: Data) -> [String: Data]? {
        guard let obj = (try? JSONSerialization.jsonObject(with: data)) as? [String: Any] else { return nil }
        guard obj["type"] as? String == keyBackupType else { return nil }
        let version = (obj["version"] as? Int) ?? (obj["version"] as? NSNumber)?.intValue
        guard version == keyBackupVersion else { return nil }
        guard let keyMap = obj["keys"] as? [String: Any] else { return nil }
        var out: [String: Data] = [:]
        for (channelId, entryAny) in keyMap {
            guard let entry = entryAny as? [String: Any],
                  let b64 = entry["keyBase64"] as? String,
                  let bytes = Data(base64Encoded: b64), bytes.count == keyBytes else { continue }
            out[channelId] = bytes
        }
        return out
    }
}
