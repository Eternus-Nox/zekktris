/**
 * Migration runner
 * ----------------
 * Used in two contexts:
 *   1. Local dev / CI: `pnpm db:migrate` (runs the script as an entry point)
 *   2. Production: api container calls `runMigrations()` from its startup
 *      checks, so the operator sees the migration step tick green in the
 *      docker logs alongside everything else that has to be healthy before
 *      the HTTP server starts accepting traffic.
 *
 * Idempotent — drizzle's migrator records applied versions in
 * `__drizzle_migrations` and skips ones it's already run.
 *
 * Migrations are SQL files in ./migrations generated by drizzle-kit
 * (`pnpm db:generate`). The folder must ship alongside this module in any
 * deployment artifact; the resolver below derives its path from
 * `import.meta.url` so it works whether the package runs from source
 * (tsx) or from a build output.
 */

import { drizzle } from 'drizzle-orm/postgres-js';
import { migrate } from 'drizzle-orm/postgres-js/migrator';
import postgres from 'postgres';

export interface MigrationResult {
  /** Wall-clock duration in ms. */
  durationMs: number;
}

/**
 * Apply any pending migrations against `databaseUrl`. Throws on failure;
 * the caller decides whether to abort the boot (production) or surface a
 * red startup-check entry (dev).
 */
export async function runMigrations(databaseUrl: string): Promise<MigrationResult> {
  const start = Date.now();
  // Migrations use a separate, single-connection client so they don't tie
  // up the application pool. We close it explicitly in `finally`.
  const client = postgres(databaseUrl, { max: 1 });
  try {
    const db = drizzle(client);
    await migrate(db, {
      migrationsFolder: new URL('../migrations', import.meta.url).pathname,
    });
    return { durationMs: Date.now() - start };
  } finally {
    await client.end({ timeout: 5 });
  }
}

// ── CLI entrypoint ─────────────────────────────────────────────────────────
// Only runs when invoked directly (e.g. `tsx packages/db/src/migrate.ts`),
// not when imported. The check is import.meta.url === pathToFileURL(argv[1]).

import { pathToFileURL } from 'node:url';
import { argv } from 'node:process';

const invokedDirectly = argv[1] && import.meta.url === pathToFileURL(argv[1]).href;
if (invokedDirectly) {
  const url = process.env.DATABASE_URL;
  if (!url) {
    console.error('DATABASE_URL is not set');
    process.exit(1);
  }
  console.log('▶ Running database migrations…');
  runMigrations(url)
    .then((r) => {
      console.log(`✓ Migrations applied in ${r.durationMs} ms`);
    })
    .catch((err) => {
      console.error('✗ Migration failed:', err);
      process.exit(1);
    });
}

